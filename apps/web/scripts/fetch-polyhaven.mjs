// Downloads the Poly Haven (CC0) assets listed in polyhaven-manifest.json into public/models/wedding/polyhaven and writes
// src/wedding/studio/assets/registry.json. Downloads are untrusted data: only expected hosts/extensions, size caps, no execution.
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, '..');
const outRoot = path.join(web, 'public/models/wedding');
const registryPath = path.join(web, 'src/wedding/studio/assets/registry.json');
const manifest = JSON.parse(readFileSync(path.join(here, 'polyhaven-manifest.json'), 'utf8'));
const UA = { 'user-agent': 'wedding-os-dev' };
const EXT = new Set(['.gltf', '.bin', '.jpg', '.png', '.hdr']);
const MAX_FILE = 6 * 1024 * 1024;
const HOST = /^https:\/\/dl\.polyhaven\.org\//;
const LICENCE = { licence: 'CC0-1.0', licenceUrl: 'https://polyhaven.com/license' };
const res = manifest.resolution ?? '1k';

const api = async (p) => { const r = await fetch(`https://api.polyhaven.com${p}`, { headers: UA }); if (!r.ok) throw new Error(`${p}: ${r.status}`); return r.json(); };
const sha = (b) => createHash('sha256').update(b).digest('hex');

async function download(url, rel) {
  if (!HOST.test(url)) throw new Error(`unexpected host ${url}`);
  const ext = path.extname(new URL(url).pathname).toLowerCase();
  if (!EXT.has(ext)) throw new Error(`unexpected extension ${ext} for ${url}`);
  const dest = path.join(outRoot, rel);
  if (existsSync(dest)) { const b = readFileSync(dest); return { path: rel, sha256: sha(b), bytes: b.length }; }
  const r = await fetch(url, { headers: UA });
  if (!r.ok) throw new Error(`${url}: ${r.status}`);
  const buf = Buffer.from(await r.arrayBuffer());
  if (buf.length > MAX_FILE) throw new Error(`${url} too large (${buf.length})`);
  if (ext === '.gltf') { const j = JSON.parse(buf.toString('utf8')); if (!j.asset) throw new Error('not a glTF'); }
  mkdirSync(path.dirname(dest), { recursive: true });
  writeFileSync(dest, buf);
  return { path: rel, sha256: sha(buf), bytes: buf.length };
}

const assets = [];
const meta = async (id, kind) => {
  const info = await api(`/info/${id}`);
  const t = { models: 2, textures: 1, hdris: 0 }[kind];
  if (info.type !== t) throw new Error(`${id} is not a ${kind}`);
  return { author: Object.keys(info.authors ?? {}).join(', ') || 'Poly Haven', sourceUrl: `https://polyhaven.com/a/${id}` };
};

for (const m of manifest.models) {
  const f = await api(`/files/${m.id}`);
  const g = f.gltf?.[res]?.gltf;
  if (!g) throw new Error(`${m.id}: no ${res} gltf`);
  const base = `polyhaven/models/${m.id}`;
  const files = [await download(g.url, `${base}/${m.id}_${res}.gltf`)];
  for (const [rel, inc] of Object.entries(g.include ?? {})) files.push(await download(inc.url, `${base}/${rel}`));
  assets.push({ assetId: m.id, kind: 'model', file: files[0].path, includes: files.slice(1), catalogIds: m.catalogIds, ...(await meta(m.id, 'models')), ...LICENCE, attributionRequired: false, attributionText: '', checkedOn: new Date().toISOString().slice(0, 10), sha256: files[0].sha256 });
}
for (const t of manifest.textures) {
  const f = await api(`/files/${t.id}`);
  const files = [];
  for (const [key, tag] of [['Diffuse', 'diff'], ['nor_gl', 'nor'], ['arm', 'arm']]) {
    const u = f[key]?.[res]?.jpg?.url;
    if (!u) throw new Error(`${t.id}: missing ${key}`);
    files.push(await download(u, `polyhaven/textures/${t.id}/${t.id}_${tag}_${res}.jpg`));
  }
  assets.push({ assetId: t.id, kind: 'texture', file: files[0].path, includes: files.slice(1), catalogIds: [], use: t.use, ...(await meta(t.id, 'textures')), ...LICENCE, attributionRequired: false, attributionText: '', checkedOn: new Date().toISOString().slice(0, 10), sha256: files[0].sha256 });
}
for (const h of manifest.hdris) {
  const f = await api(`/files/${h.id}`);
  const u = f.hdri?.[res]?.hdr?.url;
  if (!u) throw new Error(`${h.id}: no ${res} hdr`);
  const file = await download(u, `polyhaven/hdris/${h.id}_${res}.hdr`);
  assets.push({ assetId: h.id, kind: 'hdri', file: file.path, includes: [], catalogIds: [], use: h.use, ...(await meta(h.id, 'hdris')), ...LICENCE, attributionRequired: false, attributionText: '', checkedOn: new Date().toISOString().slice(0, 10), sha256: file.sha256 });
}

writeFileSync(registryPath, `${JSON.stringify({ $comment: 'Licence registry for third-party assets (generated by scripts/fetch-polyhaven.mjs). Only CC0, CC-BY, MIT and Apache-2.0 are allowed; each entry lists every file with its sha256.', assets }, null, 2)}\n`);
const total = assets.reduce((n, a) => n + (a.includes ?? []).reduce((s, i) => s + i.bytes, 0), 0);
console.log(`registry: ${assets.length} assets written. Extra files total ${(total / 1048576).toFixed(1)} MB (plus main files).`);
